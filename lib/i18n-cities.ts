const BY_LOCALE: Record<NativeLocale, Record<string, TranslatedCity>> = { hy: HY, ru: RU };

export const CITY_SEGMENTS = CITY_PAGES.map((c) => c.href.slice(1));

export function cityBySegment(segment: string): CityPage | undefined {
  return CITY_PAGES.find((c) => c.href === `/${segment}`);
}

export function translatedCity(locale: NativeLocale, segment: string): CityPage | undefined {
  const english = cityBySegment(segment);
  if (!english) return undefined;
  const translated = BY_LOCALE[locale][english.slug];
  if (!translated) return undefined;
  return { ...translated, slug: english.slug, href: `/${locale}/${segment}` };
}

export function translatedCities(locale: NativeLocale): CityPage[] {
  return CITY_PAGES.map((c) => ({
    ...BY_LOCALE[locale][c.slug],
    slug: c.slug,
    href: `/${locale}${c.href}`,
  }));
}
